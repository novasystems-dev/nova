{-# LANGUAGE OverloadedStrings #-}
{-# LANGUAGE RecordWildCards #-}

module Nova.Codegen.LLVM
    ( emitLLVMProgram
    ) where

import Data.Text (Text)
import qualified Data.Text as T

import Nova.Syntax.Span
import Nova.Syntax.Token
import Nova.Syntax.AST

emitLLVMProgram :: Program -> Text
emitLLVMProgram (Program items) =
    T.unlines
        [ "; ========================================================="
        , "; Generated by NOVAC Genesis Stage 0 (Nova -> LLVM IR Backend)"
        , "; Target: Generic 64-bit LLVM IR"
        , "; ========================================================="
        , "source_filename = \"nova_module.nova\""
        , "target datalayout = \"e-m:e-p270:32:32-p271:32:32-p272:64:64-i64:64-f80:128-n8:16:32:64-S128\""
        , "target triple = \"x86_64-unknown-linux-gnu\""
        , ""
        , "; External Nova Runtime Declarations"
        , "declare void @nova_print(i8*)"
        , "declare void @nova_print_int(i64)"
        , "declare void @nova_print_bool(i1)"
        , "declare i8* @malloc(i64)"
        , "declare void @free(i8*)"
        , ""
        , "; Global String Constants"
        , "@.str_true  = private unnamed_addr constant [5 x i8] c\"true\\00\", align 1"
        , "@.str_false = private unnamed_addr constant [6 x i8] c\"false\\00\", align 1"
        , ""
        , "; Function Implementations"
        , T.unlines (map emitTopLevelFn items)
        ]

emitTopLevelFn :: Spanned TopLevel -> Text
emitTopLevelFn (Spanned (TopFn FnDecl{..}) _) =
    let retTy = case fnReturnType of
            Just (TyNamed "Int")   -> "i64"
            Just (TyNamed "Bool")  -> "i1"
            Just (TyNamed "Float") -> "double"
            Just (TyNamed "Void")  -> "void"
            _                      -> "void"
        llvmFnName = if fnName == "main" then "main" else "nova_" <> fnName
        paramList = T.intercalate ", " [ emitLLVMParam p | p <- fnParams ]
        bodyCode = emitLLVMBody fnBody
    in T.unlines
        [ "define " <> retTy <> " @" <> llvmFnName <> "(" <> paramList <> ") {"
        , "entry:"
        , bodyCode
        , if retTy == "void" then "  ret void" else if retTy == "i64" then "  ret i64 0" else "  ret void"
        , "}"
        ]
emitTopLevelFn _ = ""

emitLLVMParam :: Param -> Text
emitLLVMParam Param{..} =
    emitLLVMType paramType <> " %" <> paramName

emitLLVMType :: TypeExpr -> Text
emitLLVMType (TyNamed "Int")    = "i64"
emitLLVMType (TyNamed "Bool")   = "i1"
emitLLVMType (TyNamed "Float")  = "double"
emitLLVMType (TyNamed "String") = "i8*"
emitLLVMType _                  = "i8*"

emitLLVMBody :: [Spanned Stmt] -> Text
emitLLVMBody stmts =
    let (_, codeLines) = foldl emitStmtLine (1, []) stmts
    in T.unlines (reverse codeLines)
  where
    emitStmtLine :: (Int, [Text]) -> Spanned Stmt -> (Int, [Text])
    emitStmtLine (reg, acc) (Spanned stmt _) = case stmt of
        StmtLet (PatVar _ name) _ expr ->
            let (reg', valStr, exprCode) = emitLLVMExpr reg expr
                allocLine = "  %" <> name <> " = alloca i64, align 8"
                storeLine = "  store i64 " <> valStr <> ", i64* %" <> name <> ", align 8"
            in (reg', storeLine : allocLine : (exprCode ++ acc))

        StmtAssign (Spanned (ExprVar name) _) expr ->
            let (reg', valStr, exprCode) = emitLLVMExpr reg expr
                storeLine = "  store i64 " <> valStr <> ", i64* %" <> name <> ", align 8"
            in (reg', storeLine : (exprCode ++ acc))

        StmtReturn (Just expr) ->
            let (reg', valStr, exprCode) = emitLLVMExpr reg expr
                retLine = "  ret i64 " <> valStr
            in (reg', retLine : (exprCode ++ acc))

        StmtExpr (Spanned (ExprCall (Spanned (ExprVar "print") _) [arg]) _) ->
            let (reg', valStr, exprCode) = emitLLVMExpr reg arg
                callLine = "  call void @nova_print(i8* " <> valStr <> ")"
            in (reg', callLine : (exprCode ++ acc))

        StmtExpr (Spanned (ExprCall (Spanned (ExprVar "print_int") _) [arg]) _) ->
            let (reg', valStr, exprCode) = emitLLVMExpr reg arg
                callLine = "  call void @nova_print_int(i64 " <> valStr <> ")"
            in (reg', callLine : (exprCode ++ acc))

        _ -> (reg, acc)

emitLLVMExpr :: Int -> Spanned Expr -> (Int, Text, [Text])
emitLLVMExpr reg (Spanned expr _) = case expr of
    ExprLit (LitInt n) ->
        (reg, T.pack (show n), [])
    ExprLit (LitBool b) ->
        (reg, if b then "1" else "0", [])
    ExprVar v ->
        let r = "%r" <> T.pack (show reg)
            code = "  " <> r <> " = load i64, i64* %" <> v <> ", align 8"
        in (reg + 1, r, [code])
    ExprBinary op l r ->
        let (reg1, vL, codeL) = emitLLVMExpr reg l
            (reg2, vR, codeR) = emitLLVMExpr reg1 r
            rRes = "%r" <> T.pack (show reg2)
            opCode = case op of
                OpAdd -> "add i64 " <> vL <> ", " <> vR
                OpSub -> "sub i64 " <> vL <> ", " <> vR
                OpMul -> "mul i64 " <> vL <> ", " <> vR
                OpDiv -> "sdiv i64 " <> vL <> ", " <> vR
                OpEq  -> "icmp eq i64 " <> vL <> ", " <> vR
                _     -> "add i64 " <> vL <> ", " <> vR
            line = "  " <> rRes <> " = " <> opCode
        in (reg2 + 1, rRes, line : (codeR ++ codeL))
    _ ->
        (reg, "0", [])
