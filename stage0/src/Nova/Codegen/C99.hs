{-# LANGUAGE OverloadedStrings #-}
{-# LANGUAGE RecordWildCards #-}

module Nova.Codegen.C99
    ( emitC99Program
    , compileAndLinkC99
    ) where

import Data.Text (Text)
import qualified Data.Text as T
import System.Process (callCommand)
import System.FilePath ((</>))

import Nova.Syntax.Span
import Nova.Syntax.Token
import Nova.Syntax.AST

emitC99Program :: Program -> Text
emitC99Program (Program items) =
    T.unlines
        [ "/* ========================================================= */"
        , "/* Generated by NOVAC Genesis Stage 0 (Nova -> C99 Backend)  */"
        , "/* ========================================================= */"
        , "#include \"nova_rt.h\""
        , "#include <stdio.h>"
        , "#include <stdlib.h>"
        , "#include <stdbool.h>"
        , "#include <stdint.h>"
        , ""
        , "// Type Definitions"
        , T.unlines (map emitTopLevelType items)
        , "// Forward Declarations"
        , T.unlines (map emitForwardDecl items)
        , "// Function Implementations"
        , T.unlines (map emitTopLevelFn items)
        ]

emitForwardDecl :: Spanned TopLevel -> Text
emitForwardDecl (Spanned (TopFn FnDecl{..}) _) =
    emitC99Type (case fnReturnType of Just t -> t; Nothing -> TyNamed "Void")
    <> " nova_" <> fnName <> "(" <> emitC99Params fnParams <> ");"
emitForwardDecl _ = ""

emitTopLevelType :: Spanned TopLevel -> Text
emitTopLevelType (Spanned (TopType TypeDecl{..}) _) =
    case typeDef of
        TypeRefinement _ baseTy _ ->
            "typedef " <> emitC99Type baseTy <> " nova_type_" <> typeName <> ";\n"
        TypeStruct fields ->
            "typedef struct {\n"
            <> T.unlines [ "    " <> emitC99Type ty <> " " <> f <> ";" | (f, ty) <- fields ]
            <> "} nova_type_" <> typeName <> ";\n"
        TypeAlias ty ->
            "typedef " <> emitC99Type ty <> " nova_type_" <> typeName <> ";\n"
        _ -> ""
emitTopLevelType _ = ""

emitTopLevelFn :: Spanned TopLevel -> Text
emitTopLevelFn (Spanned (TopFn FnDecl{..}) _) =
    let isMain = fnName == "main"
        cFnName = if isMain then "main" else "nova_" <> fnName
        retTy = if isMain then "int" else emitC99Type (case fnReturnType of Just t -> t; Nothing -> TyNamed "Void")
        paramList = if isMain then "int argc, char **argv" else emitC99Params fnParams
        bodyCode = T.unlines (map emitStmt fnBody)
        mainInit = if isMain then "    nova_rt_init();\n" else ""
        mainExit = if isMain then "    nova_rt_shutdown();\n    return 0;\n" else ""
    in retTy <> " " <> cFnName <> "(" <> paramList <> ") {\n"
       <> mainInit
       <> bodyCode
       <> mainExit
       <> "}\n"
emitTopLevelFn _ = ""

emitC99Params :: [Param] -> Text
emitC99Params [] = "void"
emitC99Params ps = T.intercalate ", " [ emitC99Type paramType <> " " <> paramName | Param{..} <- ps ]

emitC99Type :: TypeExpr -> Text
emitC99Type (TyNamed name) = case name of
    "Int"    -> "int64_t"
    "Int32"  -> "int32_t"
    "Int64"  -> "int64_t"
    "UInt"   -> "uint64_t"
    "Float"  -> "double"
    "Float32"-> "float"
    "Float64"-> "double"
    "Bool"   -> "bool"
    "String" -> "const char *"
    "Void"   -> "void"
    "T"      -> "int64_t"
    other    -> "nova_type_" <> other
emitC99Type (TyList elemTy) = emitC99Type elemTy <> " *"
emitC99Type (TyCapability _ ty) = emitC99Type ty
emitC99Type (TyGeneric name _) = emitC99Type (TyNamed name)
emitC99Type _ = "void *"

emitStmt :: Spanned Stmt -> Text
emitStmt (Spanned stmt _) = case stmt of
    StmtLet pat mty expr ->
        let tyStr = case mty of
                Just t  -> emitC99Type t
                Nothing -> inferRhsType expr
            varName = case pat of
                PatVar _ name -> name
                _             -> "_tmp"
        in "    " <> tyStr <> " " <> varName <> " = " <> emitExpr expr <> ";"
    StmtAssign lhs rhs ->
        "    " <> emitExpr lhs <> " = " <> emitExpr rhs <> ";"
    StmtReturn mval ->
        case mval of
            Just val -> "    return " <> emitExpr val <> ";"
            Nothing  -> "    return;"
    StmtIf cond thenStmts elifs elseStmts ->
        "    if (" <> emitExpr cond <> ") {\n"
        <> T.unlines (map emitStmt thenStmts)
        <> "    }"
        <> T.concat [ " else if (" <> emitExpr c <> ") {\n" <> T.unlines (map emitStmt b) <> "    }" | (c, b) <- elifs ]
        <> (case elseStmts of
                Just eb -> " else {\n" <> T.unlines (map emitStmt eb) <> "    }\n"
                Nothing -> "\n")
    StmtWhile cond body ->
        "    while (" <> emitExpr cond <> ") {\n"
        <> T.unlines (map emitStmt body)
        <> "    }\n"
    StmtUnsafe _ body ->
        "    /* unsafe block */ {\n"
        <> T.unlines (map emitStmt body)
        <> "    }\n"
    StmtRegion _ body ->
        "    /* region block */ {\n"
        <> T.unlines (map emitStmt body)
        <> "    }\n"
    StmtExpr expr ->
        "    " <> emitExpr expr <> ";"
    _ -> ""

emitExpr :: Spanned Expr -> Text
emitExpr (Spanned expr _) = case expr of
    ExprLit lit -> case lit of
        LitInt n    -> T.pack (show n) <> "LL"
        LitFloat d  -> T.pack (show d)
        LitString s -> "\"" <> s <> "\""
        LitChar c   -> "'" <> T.singleton c <> "'"
        LitBool b   -> if b then "true" else "false"
    ExprVar v       -> v
    ExprBinary op lhs rhs ->
        "(" <> emitExpr lhs <> " " <> emitBinOp op <> " " <> emitExpr rhs <> ")"
    ExprUnary op operand ->
        emitUnOp op <> "(" <> emitExpr operand <> ")"
    ExprCall (Spanned (ExprVar "print") _) [arg] ->
        "nova_print_str(" <> emitExpr arg <> "); nova_print_newline()"
    ExprCall (Spanned (ExprVar "print_int") _) [arg] ->
        "nova_print_int(" <> emitExpr arg <> "); nova_print_newline()"
    ExprCall (Spanned (ExprVar "print_float") _) [arg] ->
        "nova_print_float(" <> emitExpr arg <> "); nova_print_newline()"
    ExprCall (Spanned (ExprVar "print_bool") _) [arg] ->
        "nova_print_bool(" <> emitExpr arg <> "); nova_print_newline()"
    ExprCall (Spanned (ExprVar fn) _) args ->
        "nova_" <> fn <> "(" <> T.intercalate ", " (map emitExpr args) <> ")"
    ExprCall fn args ->
        emitExpr fn <> "(" <> T.intercalate ", " (map emitExpr args) <> ")"
    ExprIndex base idx ->
        emitExpr base <> "[" <> emitExpr idx <> "]"
    ExprField base field ->
        emitExpr base <> "." <> field
    _ -> "0"

inferRhsType :: Spanned Expr -> Text
inferRhsType (Spanned (ExprLit (LitString _)) _) = "const char *"
inferRhsType (Spanned (ExprLit (LitFloat _)) _)  = "double"
inferRhsType (Spanned (ExprLit (LitBool _)) _)   = "bool"
inferRhsType (Spanned (ExprLit (LitChar _)) _)   = "char"
inferRhsType _                                   = "int64_t"

emitBinOp :: BinOp -> Text
emitBinOp OpAdd   = "+"
emitBinOp OpSub   = "-"
emitBinOp OpMul   = "*"
emitBinOp OpDiv   = "/"
emitBinOp OpMod   = "%"
emitBinOp OpEq    = "=="
emitBinOp OpNotEq = "!="
emitBinOp OpLt    = "<"
emitBinOp OpLtEq  = "<="
emitBinOp OpGt    = ">"
emitBinOp OpGtEq  = ">="
emitBinOp OpAnd   = "&&"
emitBinOp OpOr    = "||"

emitUnOp :: UnOp -> Text
emitUnOp OpNeg = "-"
emitUnOp OpNot = "!"

compileAndLinkC99 :: FilePath -> FilePath -> FilePath -> IO ()
compileAndLinkC99 cSource runtimeDir outBinary = do
    let runtimeC = runtimeDir </> "nova_rt.c"
    let cmd = "gcc -O3 -std=c99 -I" <> runtimeDir <> " " <> cSource <> " " <> runtimeC <> " -o " <> outBinary
    callCommand cmd
