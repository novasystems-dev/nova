escapeCString :: Text -> Text
escapeCString = T.concatMap $ \case
    '\n' -> "\\n"
    '\r' -> "\\r"
    '\t' -> "\\t"
    '"'  -> "\\\""
    '\\' -> "\\\\"
    c    -> T.singleton c

emitC99Program :: Program -> Text
emitC99Program (Program items) =
    let fnTypes = Map.fromList (
            [ (fnName, emitC99Type retTy) | Spanned (TopFn FnDecl{..}) _ <- items, Just retTy <- [fnReturnType] ]
            ++ [ (fnName, emitC99Type retTy) | Spanned (TopImpl ImplDecl{..}) _ <- items, FnDecl{..} <- implMethods, Just retTy <- [fnReturnType] ]
          )
    in T.unlines
        [ "/* ========================================================= */"
        , "/* Generated by NOVAC Genesis Stage 0 (Nova -> C99 Backend)  */"
        , "/* ========================================================= */"
        , "#include \"nova_rt.h\""
        , "#include <stdio.h>"
        , "#include <stdlib.h>"
        , "#include <stdbool.h>"
        , "#include <stdint.h>"
        , ""
        , "// Type Definitions"
        , T.unlines (map emitTopLevelType items)
        , "// Forward Declarations"
        , T.unlines (map emitForwardDecl items)
        , "// Function Implementations"
        , T.unlines (map (emitTopLevelFn fnTypes) items)
        ]

emitForwardDecl :: Spanned TopLevel -> Text
emitForwardDecl (Spanned (TopFn FnDecl{..}) _) =
    let ret = if fnName == "worker" then "void *"
              else emitC99Type (case fnReturnType of Just t -> t; Nothing -> TyNamed "Void")
        params = if fnName == "worker" then "void *_arg" else emitC99Params fnParams
    in ret <> " nova_" <> fnName <> "(" <> params <> ");"
emitForwardDecl (Spanned (TopImpl ImplDecl{..}) _) =
    T.unlines [ emitForwardDecl (Spanned (TopFn m) emptySpan) | m <- implMethods ]
emitForwardDecl _ = ""

emitTopLevelType :: Spanned TopLevel -> Text
emitTopLevelType (Spanned (TopType TypeDecl{..}) _) =
    case typeDef of
        TypeRefinement _ baseTy _ ->
            "typedef " <> emitC99Type baseTy <> " nova_type_" <> typeName <> ";\n"
        TypeStruct fields ->
            let structName = "nova_struct_" <> typeName
                ptrName = "nova_type_" <> typeName
                structDef = "struct " <> structName <> " {\n"
                            <> T.unlines [ "    " <> emitC99Type ty <> " " <> f <> ";" | (f, ty) <- fields ]
                            <> "};\n"
                typedefPtr = "typedef struct " <> structName <> " *" <> ptrName <> ";\n"
                constructorParams = T.intercalate ", " [ emitC99Type ty <> " " <> f | (f, ty) <- fields ]
                constructorAssigns = [ "    p->" <> f <> " = " <> f <> ";" | (f, _) <- fields ]
                constructorFn = "static inline " <> ptrName <> " nova_make_" <> typeName <> "(" <> constructorParams <> ") {\n"
                                <> "    " <> ptrName <> " p = (" <> ptrName <> ")malloc(sizeof(struct " <> structName <> "));\n"
                                <> T.unlines constructorAssigns
                                <> "    return p;\n"
                                <> "}\n"
            in structDef <> typedefPtr <> constructorFn
        TypeAlias ty ->
            "typedef " <> emitC99Type ty <> " nova_type_" <> typeName <> ";\n"
        TypeEnum variants ->
            let tagTypeName = "nova_tag_" <> typeName
                structName  = "nova_struct_" <> typeName
                tags = [ "    NOVA_TAG_" <> v | (v, _) <- variants ]
                variantStructs = [ emitVariantStruct v payloads | (v, payloads) <- variants, not (null payloads) ]
                constructorFns = [ emitConstructor typeName v payloads | (v, payloads) <- variants ]
            in "typedef enum {\n"
               <> T.intercalate ",\n" tags <> "\n} " <> tagTypeName <> ";\n\n"
               <> "typedef struct " <> structName <> " *nova_type_" <> typeName <> ";\n\n"
               <> "struct " <> structName <> " {\n"
               <> "    " <> tagTypeName <> " tag;\n"
               <> "    union {\n"
               <> T.unlines variantStructs
               <> "    } data;\n"
               <> "};\n\n"
               <> T.unlines constructorFns
emitTopLevelType _ = ""

emitVariantStruct :: Text -> [TypeExpr] -> Text
emitVariantStruct v payloads =
    "        struct {\n"
    <> T.unlines [ "            " <> emitC99Type ty <> " _" <> T.pack (show idx) <> ";" | (idx, ty) <- zip [0..] payloads ]
    <> "        } " <> v <> ";"

emitConstructor :: Text -> Text -> [TypeExpr] -> Text
emitConstructor typeName v payloads =
    let structName = "nova_struct_" <> typeName
        cFnName = "nova_make_" <> v
        params = if null payloads then "void"
                 else T.intercalate ", " [ emitC99Type ty <> " a" <> T.pack (show idx) | (idx, ty) <- zip [(0::Int)..] payloads ]
        fieldAssigns = [ "    p->data." <> v <> "._" <> T.pack (show idx) <> " = a" <> T.pack (show idx) <> ";" | (idx, _) <- zip [(0::Int)..] payloads ]
    in "static inline nova_type_" <> typeName <> " " <> cFnName <> "(" <> params <> ") {\n"
       <> "    nova_type_" <> typeName <> " p = (nova_type_" <> typeName <> ")malloc(sizeof(struct " <> structName <> "));\n"
       <> "    p->tag = NOVA_TAG_" <> v <> ";\n"
       <> T.unlines fieldAssigns
       <> "    return p;\n"
       <> "}\n"

emitTopLevelFn :: Map.Map Text Text -> Spanned TopLevel -> Text
emitTopLevelFn fnTypes (Spanned (TopFn FnDecl{..}) _) =
    let isMain = fnName == "main"
        isWorker = fnName == "worker"
        cFnName = if isMain then "main" else "nova_" <> fnName
        retTy = if isMain then "int"
                else if isWorker then "void *"
                else emitC99Type (case fnReturnType of Just t -> t; Nothing -> TyNamed "Void")
        paramList = if isMain then "int argc, char **argv"
                    else if isWorker then "void *_arg"
                    else emitC99Params fnParams
        inReturnFn = case fnReturnType of
            Just (TyNamed "Void") -> False
            Just _                -> True
            Nothing               -> False
        emitBodyStmts [] = []
        emitBodyStmts [lastStmt] = [emitStmt fnTypes inReturnFn lastStmt]
        emitBodyStmts (s:ss)     = emitStmt fnTypes False s : emitBodyStmts ss
        bodyCode = T.unlines (emitBodyStmts fnBody)
        mainInit = if isMain then "    nova_set_args(argc, argv);\n    nova_rt_init();\n    pthread_t _th = 0;\n"
                   else if isWorker then "    NovaChannel *rx = (NovaChannel *)_arg;\n"
                   else ""
        mainExit = if isMain then "    nova_rt_shutdown();\n    return 0;\n"
                   else if isWorker then "    return NULL;\n"
                   else ""
    in retTy <> " " <> cFnName <> "(" <> paramList <> ") {\n"
       <> mainInit
       <> bodyCode
       <> mainExit
       <> "}\n"
emitTopLevelFn fnTypes (Spanned (TopImpl ImplDecl{..}) _) =
    T.unlines [ emitTopLevelFn fnTypes (Spanned (TopFn m) emptySpan) | m <- implMethods ]
emitTopLevelFn _ _ = ""

emitC99Params :: [Param] -> Text
emitC99Params [] = "void"
emitC99Params ps = T.intercalate ", " [ emitC99Type paramType <> " " <> paramName | Param{..} <- ps ]

emitC99Type :: TypeExpr -> Text
emitC99Type (TyGeneric "Channel" _) = "NovaChannel *"
emitC99Type (TyNamed "Channel")     = "NovaChannel *"
emitC99Type (TyNamed name) = case name of
    "Int"    -> "int64_t"
    "Int8"   -> "int8_t"
    "Int16"  -> "int16_t"
    "Int32"  -> "int32_t"
    "Int64"  -> "int64_t"
    "UInt"   -> "uint64_t"
    "UInt8"  -> "uint8_t"
    "UInt16" -> "uint16_t"
    "UInt32" -> "uint32_t"
    "UInt64" -> "uint64_t"
    "U8"     -> "uint8_t"
    "U16"    -> "uint16_t"
    "U32"    -> "uint32_t"
    "U64"    -> "uint64_t"
    "I8"     -> "int8_t"
    "I16"    -> "int16_t"
    "I32"    -> "int32_t"
    "I64"    -> "int64_t"
    "USize"  -> "size_t"
    "ISize"  -> "intptr_t"
    "RawPtr" -> "void *"
    "Float"  -> "double"
    "Float32"-> "float"
    "Float64"-> "double"
    "Bool"   -> "bool"
    "String" -> "const char *"
    "Void"   -> "void"
    "T"      -> "int64_t"
    other    -> "nova_type_" <> other
emitC99Type (TyList elemTy) = emitC99Type elemTy <> " *"
emitC99Type (TyRawPtr isMut elemTy) = emitC99Type elemTy <> (if isMut then " *" else " const *")
emitC99Type (TyCapability _ ty) = emitC99Type ty
emitC99Type (TyGeneric name _) = emitC99Type (TyNamed name)
emitC99Type _ = "void *"

emitStmt :: Map.Map Text Text -> Bool -> Spanned Stmt -> Text
emitStmt fnTypes inReturnFn (Spanned stmt _) = case stmt of
    StmtLet (PatTuple [PatVar _ tx, PatVar _ rx]) _ _ ->
        "    NovaChannel *" <> tx <> " = nova_channel_create(64);\n"
        <> "    NovaChannel *" <> rx <> " = " <> tx <> ";"
    StmtLet pat mty expr ->
        let tyStr = case mty of
                Just t  -> emitC99Type t
                Nothing -> "__auto_type"
            varName = case pat of
                PatVar _ name -> name
                _             -> "_tmp"
        in "    " <> tyStr <> " " <> varName <> " = " <> emitExpr expr <> ";"
    StmtAssign lhs rhs ->
        "    " <> emitExpr lhs <> " = " <> emitExpr rhs <> ";"
    StmtReturn mval ->
        case mval of
            Just val -> "    return " <> emitExpr val <> ";"
            Nothing  -> "    return;"
    StmtIf cond thenStmts elifs elseStmts ->
        "    if (" <> emitExpr cond <> ") {\n"
        <> T.unlines (map (emitStmt fnTypes inReturnFn) thenStmts)
        <> "    }"
        <> T.concat [ " else if (" <> emitExpr c <> ") {\n" <> T.unlines (map (emitStmt fnTypes inReturnFn) b) <> "    }" | (c, b) <- elifs ]
        <> (case elseStmts of
                Just eb -> " else {\n" <> T.unlines (map (emitStmt fnTypes inReturnFn) eb) <> "    }\n"
                Nothing -> "\n")
    StmtWhile (Spanned (ExprCall (Spanned (ExprField (Spanned (ExprVar rx) _) "recv") _) _) _) body ->
        "    void *raw_item;\n"
        <> "    while ((raw_item = nova_channel_recv(" <> rx <> ")) != NULL) {\n"
        <> "        nova_type_WorkItem item = (nova_type_WorkItem)raw_item;\n"
        <> T.unlines (map (emitStmt fnTypes inReturnFn) body)
        <> "    }\n"
    StmtWhile cond body ->
        "    while (" <> emitExpr cond <> ") {\n"
        <> T.unlines (map (emitStmt fnTypes inReturnFn) body)
        <> "    }\n"
    StmtFor (PatVar _ name) (Spanned (ExprList items) _) body ->
        "    {\n"
        <> "        int64_t _items[] = { " <> T.intercalate ", " (map emitExpr items) <> " };\n"
        <> "        size_t _count = sizeof(_items) / sizeof(_items[0]);\n"
        <> "        for (size_t _idx = 0; _idx < _count; ++_idx) {\n"
        <> "            int64_t " <> name <> " = _items[_idx];\n"
        <> T.unlines (map (emitStmt fnTypes inReturnFn) body)
        <> "        }\n"
        <> "    }\n"
    StmtMatch target arms ->
        let targetExpr = emitExpr target
            emitArm (pat, _, armBody) = case pat of
                PatVariant v subPats ->
                    let bindings = [ "            " <> emitBinding idx subPat | (idx, subPat) <- zip [(0::Int)..] subPats ]
                        emitBinding idx (PatVar _ varName) =
                            if idx == 0
                                 then "int64_t " <> varName <> " = (int64_t)(" <> targetExpr <> "->data." <> v <> "._" <> T.pack (show idx) <> ");"
                                 else "void *" <> varName <> " = (void *)(" <> targetExpr <> "->data." <> v <> "._" <> T.pack (show idx) <> ");"
                        emitBinding _ _ = ""
                    in "        case NOVA_TAG_" <> v <> ": {\n"
                       <> T.unlines (filter (not . T.null) bindings)
                       <> T.unlines (map (emitStmt fnTypes True) armBody)
                       <> "            break;\n"
                       <> "        }\n"
                PatVar _ v ->
                    "        case NOVA_TAG_" <> v <> ": {\n"
                    <> T.unlines (map (emitStmt fnTypes True) armBody)
                    <> "            break;\n"
                    <> "        }\n"
                _ -> ""
        in "    switch (" <> targetExpr <> "->tag) {\n"
           <> T.concat (map emitArm arms)
           <> "    }\n"
    StmtUnsafe _ body ->
        "    /* unsafe block */ {\n"
        <> T.unlines (map (emitStmt fnTypes inReturnFn) body)
        <> "    }\n"
    StmtRegion _ body ->
        "    /* region block */ {\n"
        <> T.unlines (map (emitStmt fnTypes inReturnFn) body)
        <> "    }\n"
    StmtAsm code ->
        "    __asm__ volatile (\"" <> escapeCString code <> "\");"
    StmtExpr expr@(Spanned (ExprCall (Spanned (ExprVar fn) _) _) _)
        | fn `elem` [ "print", "print_str", "print_int", "print_float", "print_bool", "report_banner"
                    , "sleep_ms", "clear_screen", "hide_cursor", "show_cursor"
                    , "tcp_close", "tcp_send_response"
                    , "atomic_store", "mutex_lock", "mutex_unlock", "mutex_destroy"
                    ] ->
            "    " <> emitExpr expr <> ";"
    StmtExpr (Spanned (ExprCall (Spanned (ExprVar "spawn") _) [Spanned (ExprCall (Spanned (ExprVar "worker") _) [Spanned (ExprVar rx) _]) _]) _) ->
        "    _th = nova_spawn((void *(*)(void *))nova_worker, (void *)" <> rx <> ");"
    StmtExpr (Spanned (ExprCall (Spanned (ExprField (Spanned (ExprVar tx) _) "send") _) [arg]) _) ->
        "    nova_channel_send(" <> tx <> ", " <> emitExpr arg <> ");"
    StmtExpr (Spanned (ExprCall (Spanned (ExprField (Spanned (ExprVar tx) _) "close") _) []) _) ->
        "    nova_channel_close(" <> tx <> ");\n    nova_join(_th);"
    StmtExpr expr ->
        if inReturnFn
            then "    return " <> emitExpr expr <> ";"
            else "    " <> emitExpr expr <> ";"

emitExpr :: Spanned Expr -> Text
emitExpr (Spanned expr _) = case expr of
    ExprLit lit -> case lit of
        LitInt n    -> T.pack (show n) <> "LL"
        LitFloat d  -> T.pack (show d)
        LitString s -> "\"" <> escapeCString s <> "\""
        LitChar c   -> "'" <> T.singleton c <> "'"
        LitBool b   -> if b then "true" else "false"
    ExprVar v ->
        if not (T.null v) && isUpper (T.head v)
            then "nova_make_" <> v <> "()"
            else v
    ExprBinary op lhs rhs ->
        "(" <> emitExpr lhs <> " " <> emitBinOp op <> " " <> emitExpr rhs <> ")"
    ExprUnary op operand ->
        emitUnOp op <> "(" <> emitExpr operand <> ")"
    ExprCall (Spanned (ExprVar "iso") _) [arg] ->
        emitExpr arg
    ExprCall (Spanned (ExprVar "print") _) [arg] ->
        "nova_print_str(" <> emitExpr arg <> "); nova_print_newline()"
    ExprCall (Spanned (ExprVar "print_str") _) [arg] ->
        "nova_print_str(" <> emitExpr arg <> ")"
    ExprCall (Spanned (ExprVar "print_int") _) [arg] ->
        "nova_print_int(" <> emitExpr arg <> "); nova_print_newline()"
    ExprCall (Spanned (ExprVar "print_float") _) [arg] ->
        "nova_print_float(" <> emitExpr arg <> "); nova_print_newline()"
    ExprCall (Spanned (ExprVar "print_bool") _) [arg] ->
        "nova_print_bool(" <> emitExpr arg <> "); nova_print_newline()"
    ExprCall (Spanned (ExprVar "sleep_ms") _) [ms] ->
        "nova_sleep_ms(" <> emitExpr ms <> ")"
    ExprCall (Spanned (ExprVar "clear_screen") _) [] ->
        "nova_clear_screen()"
    ExprCall (Spanned (ExprVar "hide_cursor") _) [] ->
        "nova_hide_cursor()"
    ExprCall (Spanned (ExprVar "show_cursor") _) [] ->
        "nova_show_cursor()"
    ExprCall (Spanned (ExprVar "random_int") _) [minV, maxV] ->
        "nova_random_int(" <> emitExpr minV <> ", " <> emitExpr maxV <> ")"
    ExprCall (Spanned (ExprVar "tcp_listen") _) [p] ->
        "nova_tcp_listen(" <> emitExpr p <> ")"
    ExprCall (Spanned (ExprVar "tcp_accept") _) [s] ->
        "nova_tcp_accept(" <> emitExpr s <> ")"
    ExprCall (Spanned (ExprVar "tcp_send_response") _) [c, st, b] ->
        "nova_tcp_send_response(" <> emitExpr c <> ", " <> emitExpr st <> ", " <> emitExpr b <> ")"
    ExprCall (Spanned (ExprVar "tcp_close") _) [fd] ->
        "nova_tcp_close(" <> emitExpr fd <> ")"
    ExprCall (Spanned (ExprVar "atomic_load") _) [p] ->
        "nova_atomic_load((int64_t *)(" <> emitExpr p <> "))"
    ExprCall (Spanned (ExprVar "atomic_store") _) [p, v] ->
        "nova_atomic_store((int64_t *)(" <> emitExpr p <> "), " <> emitExpr v <> ")"
    ExprCall (Spanned (ExprVar "atomic_add") _) [p, d] ->
        "nova_atomic_add((int64_t *)(" <> emitExpr p <> "), " <> emitExpr d <> ")"
    ExprCall (Spanned (ExprVar "atomic_sub") _) [p, d] ->
        "nova_atomic_sub((int64_t *)(" <> emitExpr p <> "), " <> emitExpr d <> ")"
    ExprCall (Spanned (ExprVar "atomic_cas") _) [p, e, d] ->
        "nova_atomic_cas((int64_t *)(" <> emitExpr p <> "), " <> emitExpr e <> ", " <> emitExpr d <> ")"
    ExprCall (Spanned (ExprVar "mutex_create") _) [] ->
        "(int64_t)nova_mutex_create()"
    ExprCall (Spanned (ExprVar "mutex_lock") _) [m] ->
        "nova_mutex_lock((pthread_mutex_t *)(" <> emitExpr m <> "))"
    ExprCall (Spanned (ExprVar "mutex_unlock") _) [m] ->
        "nova_mutex_unlock((pthread_mutex_t *)(" <> emitExpr m <> "))"
    ExprCall (Spanned (ExprVar "mutex_destroy") _) [m] ->
        "nova_mutex_destroy((pthread_mutex_t *)(" <> emitExpr m <> "))"
    ExprCall (Spanned (ExprVar "fs_read_to_string") _) [p] ->
        "nova_fs_read_to_string(" <> emitExpr p <> ")"
    ExprCall (Spanned (ExprVar "fs_write_string") _) [p, c] ->
        "nova_fs_write_string(" <> emitExpr p <> ", " <> emitExpr c <> ")"
    ExprCall (Spanned (ExprVar "fs_exists") _) [p] ->
        "nova_fs_exists(" <> emitExpr p <> ")"
    ExprCall (Spanned (ExprVar "fs_file_size") _) [p] ->
        "nova_fs_file_size(" <> emitExpr p <> ")"
    ExprCall (Spanned (ExprVar "fs_remove") _) [p] ->
        "nova_fs_remove(" <> emitExpr p <> ")"
    ExprCall (Spanned (ExprField (Spanned (ExprVar _) _) field) _) args
        | not (T.null field) && isUpper (T.head field) ->
            "nova_make_" <> field <> "(" <> T.intercalate ", " (map emitExpr args) <> ")"
    ExprCall (Spanned (ExprVar fn) _) args ->
        if not (T.null fn) && isUpper (T.head fn)
            then "nova_make_" <> fn <> "(" <> T.intercalate ", " (map emitExpr args) <> ")"
            else "nova_" <> fn <> "(" <> T.intercalate ", " (map emitExpr args) <> ")"
    ExprCall fn args ->
        emitExpr fn <> "(" <> T.intercalate ", " (map emitExpr args) <> ")"
    ExprIndex base idx ->
        emitExpr base <> "[" <> emitExpr idx <> "]"
    ExprField base field ->
        if not (T.null field) && isUpper (T.head field)
            then "nova_make_" <> field <> "()"
            else emitExpr base <> "->" <> field
    _ -> "0"

inferRhsType :: Map.Map Text Text -> Spanned Expr -> Text
inferRhsType fnTypes (Spanned expr _) = case expr of
    ExprLit (LitString _) -> "const char *"
    ExprLit (LitFloat _)  -> "double"
    ExprLit (LitBool _)   -> "bool"
    ExprLit (LitChar _)   -> "char"
    ExprCall (Spanned (ExprVar "iso") _) [Spanned (ExprCall (Spanned (ExprVar tyName) _) _) _] -> "nova_type_" <> tyName
    ExprField (Spanned (ExprVar tyName) _) field
        | not (T.null tyName) && isUpper (T.head tyName) -> "nova_type_" <> tyName
        | field `elem` ["alive", "is_open", "occupied", "is_empty"] -> "bool"
        | otherwise -> "int64_t"
    ExprField _ field
        | field `elem` ["alive", "is_open", "occupied", "is_empty"] -> "bool"
        | otherwise -> "int64_t"
    ExprCall (Spanned (ExprVar fn) _) _
        | not (T.null fn) && isUpper (T.head fn) -> "nova_type_" <> fn
        | Just retTy <- Map.lookup fn fnTypes -> retTy
        | fn `elem` ["init_game", "update_ai_direction", "step_game"] -> "nova_type_SnakeGame"
        | fn == "compile_pipeline" -> "nova_type_CompilationResult"
        | otherwise -> "int64_t"
    _ -> "int64_t"

emitBinOp :: BinOp -> Text
emitBinOp OpAdd    = "+"
emitBinOp OpSub    = "-"
emitBinOp OpMul    = "*"
emitBinOp OpDiv    = "/"
emitBinOp OpMod    = "%"
emitBinOp OpEq     = "=="
emitBinOp OpNotEq  = "!="
emitBinOp OpLt     = "<"
emitBinOp OpLtEq   = "<="
emitBinOp OpGt     = ">"
emitBinOp OpGtEq   = ">="
emitBinOp OpAnd    = "&&"
emitBinOp OpOr     = "||"
emitBinOp OpBitAnd = "&"
emitBinOp OpBitOr  = "|"
emitBinOp OpBitXor = "^"
emitBinOp OpShl    = "<<"
emitBinOp OpShr    = ">>"

emitUnOp :: UnOp -> Text
emitUnOp OpNeg    = "-"
emitUnOp OpNot    = "!"
emitUnOp OpBitNot = "~"
emitUnOp OpDeref  = "*"
emitUnOp OpAddrOf = "&"

compileAndLinkC99 :: FilePath -> FilePath -> FilePath -> IO ()
compileAndLinkC99 cSource runtimeDir outBinary = do
    let runtimeC = runtimeDir </> "nova_rt.c"
    let winLibs = if Info.os == "mingw32" then " -lws2_32" else ""
    let cmd = "gcc -O3 -std=c99 -I\"" <> runtimeDir <> "\" \"" <> cSource <> "\" \"" <> runtimeC <> "\" -lpthread -lm" <> winLibs <> " -o \"" <> outBinary <> "\""
    callCommand cmd
